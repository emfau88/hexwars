import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from '@playwright/test';
const base=process.env.FACTORY_URL||'http://127.0.0.1:4181/factory-preview.html';
const out=process.env.FACTORY_QA_OUTPUT||'docs/factory-model/qa/';
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true}),errors=[],hostWarnings=[],checks=[];
try{
 const p=await browser.newPage({viewport:{width:1500,height:1050}});
 p.on('pageerror',e=>errors.push(e.message));
 p.on('requestfailed',r=>(r.url().startsWith(new URL('.',base).href)?errors:hostWarnings).push(r.url()+': '+r.failure()?.errorText));
 await p.goto(base,{timeout:90000});
 const gate=p.getByText('Open the page',{exact:true});if(await gate.count())await gate.click();
 await p.waitForFunction(()=>window.__FACTORY_PREVIEW__,null,{timeout:90000});
 const state=()=>p.evaluate(()=>window.__FACTORY_PREVIEW__.diagnostics());
 const settle=()=>p.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
 await settle();
 const closed=await state();assert.equal(closed.door,0);assert.equal(closed.factories,1);
 await p.screenshot({path:out+'closed.png'});
 await p.locator('#open').click();await settle();const open=await state();assert.equal(open.door,1);
 for(let i=0;i<4;i++)assert.ok(open.doorNodes[0][i].position[1]>closed.doorNodes[0][i].position[1]);
 await p.screenshot({path:out+'open.png'});
 await p.locator('#close').click();await settle();assert.deepEqual((await state()).doorNodes,closed.doorNodes);
 checks.push('Actual GLB loads; all four exported segments move and close exactly');
 const camera=(await state()).camera;
 await p.mouse.move(1000,600);await p.mouse.down();await p.mouse.move(1120,640,{steps:8});await p.mouse.up();await settle();
 assert.notDeepEqual((await state()).camera,camera);await p.locator('[data-camera=hero]').click();
 checks.push('Pointer drag rotates the actual model');
 for(const role of ['drone','mech','rail']){
  await p.locator('#module').selectOption(role);await settle();assert.deepEqual((await state()).visibleModule,[[role]]);
  await p.locator('[data-camera=game]').click();await settle();await p.screenshot({path:out+'module-'+role+'.png'});
 }
 await p.locator('#module').selectOption('drone');await p.locator('[data-camera=hero]').click();
 await p.locator('#team').selectOption('blue');await p.locator('#open').click();await settle();
 assert.ok((await state()).materials[0].filter(m=>m.name==='Team').every(m=>m.color==='469dce'));
 await p.screenshot({path:out+'blue.png'});
 await p.locator('#ghost').check();await settle();
 assert.ok((await state()).materials[0].every(m=>m.opacity===.34&&m.depthWrite===false));
 await p.screenshot({path:out+'ghost.png'});await p.locator('#ghost').uncheck();
 assert.ok((await state()).materials[0].every(m=>m.opacity===1&&m.depthWrite===true));
 checks.push('Three separate modules visible from game camera, blue material variant and reversible construction transparency');
 await p.locator('#team').selectOption('orange');await p.locator('#scene').selectOption('compare');await settle();
 await p.screenshot({path:out+'compare.png'});checks.push('Actual HQ and mech loaded at unchanged game normalization, beside the factory');
 await p.locator('#scene').selectOption('single');await p.locator('#open').click();await p.locator('#walk').click();await p.waitForTimeout(1000);
 assert.equal((await state()).walking,true);await p.screenshot({path:out+'mech-clearance.png'});await p.locator('#walk').click();
 await p.locator('#scene').selectOption('eight');await p.locator('#open').click();await settle();
 const eight=await state();assert.equal(eight.factories,8);assert.ok(eight.drawCalls<=40);assert.ok(eight.batches>0);
 assert.equal(new Set(eight.meshes.map(m=>m.geometry)).size,closed.meshes.length);
 await p.evaluate(()=>window.__FACTORY_PREVIEW__.setFactoryDoor(0,0));
 const independent=await state();assert.notDeepEqual(independent.doorNodes[0],independent.doorNodes[1]);assert.deepEqual(independent.doorNodes[1],independent.doorNodes[7]);
 await p.screenshot({path:out+'eight.png'});
 checks.push('Eight visible factories share geometry and textures; first gate can close independently');
 await p.locator('[data-camera=rear]').click();await p.locator('#scene').selectOption('single');await p.locator('[data-camera=rear]').click();await settle();
 await p.screenshot({path:out+'rear.png'});
 const glb=await p.request.get(new URL('public/models/factory-preview/factory.glb',base).href),blend=await p.request.get(new URL('art/factory-v1/factory-source.blend',base).href);
 assert.equal(glb.status(),200);assert.equal(blend.status(),200);assert.ok((await blend.body()).length>100000);
 checks.push('GLB and editable Blender source downloads resolve');
 await p.setViewportSize({width:390,height:844});await settle();
 assert.ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await p.screenshot({path:out+'mobile.png'});checks.push('Portrait viewer has no horizontal overflow');
 assert.deepEqual(errors,[]);
 const result={url:base,checks,errors,hostWarnings,baseAsset:closed.manifest.assets[0],eight:{drawCalls:eight.drawCalls,geometries:eight.geometries,textures:eight.textures,uniqueMeshGeometries:new Set(eight.meshes.map(m=>m.geometry)).size}};
 await fs.writeFile(out+'browser.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result,null,2));
}finally{await browser.close();}
